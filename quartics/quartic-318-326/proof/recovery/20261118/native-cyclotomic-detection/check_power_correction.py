"""Finite check with an actual larger acting group after taking roots."""
from itertools import product
import json
q=range(2); g=range(4); Z=range(8)
def d2(b,x,y,z,order,modulus):
    return (pow(3,x,modulus)*b(y,z)-b((x+y)%order,z)+b(x,(y+z)%order)-b(x,y))%modulus
def d3(c,x,y,z,t,order,modulus):
    return (pow(3,x,modulus)*c(y,z,t)-c((x+y)%order,z,t)+c(x,(y+z)%order,t)-c(x,y,(z+t)%order)+c(x,y,z))%modulus
N=drifting=0
for a in product(Z,repeat=4):
    b0=lambda x,y:a[x*2+y]
    # The action 3 gives ker(1+3)=2Z/8=(3-1)Z/8; no quotient H3 here.
    c=lambda x,y,z:d2(b0,x,y,z,2,8)
    assert all(not d3(c,*t,2,8) for t in product(q,repeat=4))
    s=lambda x,y:(-sum(c(x,y,t) for t in q))%8
    assert all(d2(s,*t,2,8)==2*c(*t)%8 for t in product(q,repeat=3))
    # i:A=Z/8 -> U=Z/16 multiplication by 2. Act by 3 on U on C4;
    # C4 kernel of C4->C2 is generated by sigma^2, multiplication by 9.
    b=lambda x,y:s(x%2,y%2)
    z=lambda x,y,t:(2*c(x%2,y%2,t%2)-d2(b,x,y,t,4,16))%16
    assert all(2*z(*t)%16==0 for t in product(g,repeat=3))
    assert all(not d3(z,*t,4,16) for t in product(g,repeat=4))
    drifting+=any(9*b(x,y)%16!=b(x,y) for x,y in product(q,repeat=2))
    N+=1
print(json.dumps(dict(exact_pair_tables=N,coefficient_root_not_fixed_by_old_kernel=drifting),indent=2))
